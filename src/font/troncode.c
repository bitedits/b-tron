TC utf8_to_tc(const char *utf8_str, int *bytes_consumed) {
    if (!utf8_str || !*utf8_str) {
        if (bytes_consumed) *bytes_consumed = 0;
        return 0;
    }

    unsigned char c = (unsigned char)utf8_str[0];
    if (c < 0x80) {
        if (bytes_consumed) *bytes_consumed = 1;
        return (TC)c;
    } else if ((c & 0xE0) == 0xC0) {
        if (bytes_consumed) *bytes_consumed = 2;
        return 0x2121; /* Generic Kanji / Kana placeholder */
    } else if ((c & 0xF0) == 0xE0) {
        if (bytes_consumed) *bytes_consumed = 3;
        return 0x2121;
    }

    if (bytes_consumed) *bytes_consumed = 1;
    return '?';
}

const UB* get_glyph_bitmap(TC code, H *out_width, H *out_height) {
    if (code < 128) {
        if (out_width) *out_width = 8;
        if (out_height) *out_height = 16;
        return font_ascii_8x16[code];
    }

    /* Kanji / Kana fallback 16x16 box bitmap */
    static const UB kanji_box_16x16[16] = {
        0xFF, 0x81, 0x81, 0xBD, 0xA5, 0xA5, 0xBD, 0x81,
        0x81, 0xBD, 0xA5, 0xA5, 0xBD, 0x81, 0x81, 0xFF
    };
    if (out_width) *out_width = 16;
    if (out_height) *out_height = 16;
    return kanji_box_16x16;
}

ER drw_tc_string(GDEV *dev, H x, H y, const char *text, COLOR fg_col, COLOR bg_col) {
    if (!dev || !text || !dev->pixels) return E_PAR;

    H cur_x = x;
    H cur_y = y;
    const char *p = text;
    COLOR *pix = dev->pixels;
    H width = dev->width;

    while (*p) {
        if (*p == '\n') {
            cur_x = x;
            cur_y += 16;
            p++;
            continue;
        }

        int consumed = 0;
        TC code = utf8_to_tc(p, &consumed);
        p += (consumed > 0 ? consumed : 1);

        H gw = 8, gh = 16;
        const UB *bmp = get_glyph_bitmap(code, &gw, &gh);

        for (int row = 0; row < gh; row++) {
            UB line = bmp[row];
            for (int col = 0; col < gw; col++) {
                H px = cur_x + col;
                H py = cur_y + row;
                if (px >= dev->clip.left && px < dev->clip.right &&
                    py >= dev->clip.top && py < dev->clip.bottom) {
                    if (line & (0x80 >> (col % 8))) {
                        pix[py * width + px] = fg_col;
                    } else if (bg_col != 0x00000000) {
                        pix[py * width + px] = bg_col;
                    }
                }
            }
        }
        cur_x += gw;
    }

    return E_OK;
}
