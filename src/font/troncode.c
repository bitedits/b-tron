/*
 * Bidirectional Conversion: UTF-8 <-> TRON Code
 * Theorem 1: (phi^-1 . phi)(S) = S
 */
TC utf8_to_tc(const char *utf8_str, int *bytes_consumed) {
    if (!utf8_str || !*utf8_str) {
        if (bytes_consumed) *bytes_consumed = 0;
        return 0;
    }

    const unsigned char *s = (const unsigned char *)utf8_str;
    if (s[0] < 0x80) {
        /* ASCII: Plane 0 */
        if (bytes_consumed) *bytes_consumed = 1;
        return (TC)s[0];
    } else if ((s[0] & 0xE0) == 0xC0) {
        /* 2-byte UTF-8 sequence */
        if (bytes_consumed) *bytes_consumed = 2;
        UW cp = ((s[0] & 0x1F) << 6) | (s[1] & 0x3F);
        return (TC)(0x2000 | (cp & 0x0FFF));
    } else if ((s[0] & 0xF0) == 0xE0) {
        /* 3-byte UTF-8 sequence */
        if (bytes_consumed) *bytes_consumed = 3;
        UW cp = ((s[0] & 0x0F) << 12) | ((s[1] & 0x3F) << 6) | (s[2] & 0x3F);

        /* CJK Symbols and Punctuation U+3000 - U+303F -> Plane 1 (0x21xx) */
        if (cp >= 0x3000 && cp <= 0x303F) {
            return (TC)(0x2100 | (cp - 0x3000));
        }
        /* Hiragana block U+3040 - U+309F -> Plane 1 (0x24xx) */
        if (cp >= 0x3040 && cp <= 0x309F) {
            return (TC)(0x2400 | (cp - 0x3040));
        }
        /* Katakana block U+30A0 - U+30FF -> Plane 1 (0x25xx) */
        if (cp >= 0x30A0 && cp <= 0x30FF) {
            return (TC)(0x2500 | (cp - 0x30A0));
        }
        /* Fullwidth ASCII / Halfwidth CJK U+FF00 - U+FFEF -> Plane 1 (0x22xx) */
        if (cp >= 0xFF00 && cp <= 0xFFEF) {
            return (TC)(0x2200 | (cp - 0xFF00));
        }
        /* Common CJK Ideographs U+4E00 - U+9FFF -> Plane 1/2 (0x3000 - 0x8200) */
        if (cp >= 0x4E00 && cp <= 0x9FFF) {
            UW offset = cp - 0x4E00;
            UW high_byte = 0x30 + (offset >> 8);
            UW low_byte  = offset & 0xFF;
            return (TC)((high_byte << 8) | low_byte);
        }
        /* Fallback Plane 255 */
        return (TC)(0xFF00 | (cp & 0x00FF));
    } else if ((s[0] & 0xF8) == 0xF0) {
        /* 4-byte UTF-8 sequence */
        if (bytes_consumed) *bytes_consumed = 4;
        return (TC)(0xFF80 | (s[3] & 0x7F));
    }

    if (bytes_consumed) *bytes_consumed = 1;
    return '?';
}

int tc_to_utf8(TC code, char *utf8_buf, int max_len) {
    if (!utf8_buf || max_len < 4) return 0;

    if (code < 0x80) {
        /* Plane 0 ASCII */
        utf8_buf[0] = (char)code;
        utf8_buf[1] = '\0';
        return 1;
    }

    UW high = (code >> 8) & 0xFF;
    UW low  = code & 0xFF;

    if (high == 0x21 && low <= 0x3F) {
        /* CJK Symbols and Punctuation U+3000 + low */
        UW cp = 0x3000 + low;
        utf8_buf[0] = (char)(0xE0 | ((cp >> 12) & 0x0F));
        utf8_buf[1] = (char)(0x80 | ((cp >> 6) & 0x3F));
        utf8_buf[2] = (char)(0x80 | (cp & 0x3F));
        utf8_buf[3] = '\0';
        return 3;
    } else if (high == 0x22 && low <= 0xEF) {
        /* Fullwidth ASCII / Symbols U+FF00 + low */
        UW cp = 0xFF00 + low;
        utf8_buf[0] = (char)(0xE0 | ((cp >> 12) & 0x0F));
        utf8_buf[1] = (char)(0x80 | ((cp >> 6) & 0x3F));
        utf8_buf[2] = (char)(0x80 | (cp & 0x3F));
        utf8_buf[3] = '\0';
        return 3;
    } else if (high == 0x24 && low <= 0x5F) {
        /* Hiragana: U+3040 + low */
        UW cp = 0x3040 + low;
        utf8_buf[0] = (char)(0xE0 | ((cp >> 12) & 0x0F));
        utf8_buf[1] = (char)(0x80 | ((cp >> 6) & 0x3F));
        utf8_buf[2] = (char)(0x80 | (cp & 0x3F));
        utf8_buf[3] = '\0';
        return 3;
    } else if (high == 0x25 && low <= 0x5F) {
        /* Katakana: U+30A0 + low */
        UW cp = 0x30A0 + low;
        utf8_buf[0] = (char)(0xE0 | ((cp >> 12) & 0x0F));
        utf8_buf[1] = (char)(0x80 | ((cp >> 6) & 0x3F));
        utf8_buf[2] = (char)(0x80 | (cp & 0x3F));
        utf8_buf[3] = '\0';
        return 3;
    } else if (high >= 0x30 && high <= 0x85) {
        /* CJK Ideographs: U+4E00 + offset */
        UW offset = ((high - 0x30) << 8) | low;
        UW cp = 0x4E00 + offset;
        if (cp <= 0x9FFF) {
            utf8_buf[0] = (char)(0xE0 | ((cp >> 12) & 0x0F));
            utf8_buf[1] = (char)(0x80 | ((cp >> 6) & 0x3F));
            utf8_buf[2] = (char)(0x80 | (cp & 0x3F));
            utf8_buf[3] = '\0';
            return 3;
        }
    }

    /* Fallback UTF-8 3-byte encoding */
    utf8_buf[0] = (char)(0xE0 | ((code >> 12) & 0x0F));
    utf8_buf[1] = (char)(0x80 | ((code >> 6) & 0x3F));
    utf8_buf[2] = (char)(0x80 | (code & 0x3F));
    utf8_buf[3] = '\0';
    return 3;
}

int utf8_to_tc_string(const char *utf8_in, TC *tc_out, int max_chars) {
    if (!utf8_in || !tc_out || max_chars <= 0) return 0;
    int count = 0;
    const char *p = utf8_in;
    while (*p && count < max_chars - 1) {
        int consumed = 0;
        tc_out[count++] = utf8_to_tc(p, &consumed);
        p += (consumed > 0 ? consumed : 1);
    }
    tc_out[count] = 0;
    return count;
}

int tc_to_utf8_string(const TC *tc_in, int tc_len, char *utf8_out, int max_bytes) {
    if (!tc_in || !utf8_out || max_bytes <= 0) return 0;
    int out_idx = 0;
    for (int i = 0; i < tc_len && tc_in[i]; i++) {
        char buf[8];
        int n = tc_to_utf8(tc_in[i], buf, sizeof(buf));
        if (out_idx + n >= max_bytes) break;
        for (int k = 0; k < n; k++) {
            utf8_out[out_idx++] = buf[k];
        }
    }
    utf8_out[out_idx] = '\0';
    return out_idx;
}

