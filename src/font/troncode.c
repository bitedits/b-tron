/* Procedural Kanji / Japanese 16x16 Glyph Synthesizer */
static UB g_glyph_buffer[32];

static const UB* synthesize_japanese_glyph(TC code) {
    UW high = (code >> 8) & 0xFF;
    UW low  = code & 0xFF;

    /* Specific known symbols */
    if (high == 0x21) {
        if (low == 0x01) return glyph_jp_comma;        /* 、 */
        if (low == 0x02) return glyph_jp_period;       /* 。 */
        if (low == 0x0C) return glyph_corner_open;     /* 「 */
        if (low == 0x0D) return glyph_corner_close;    /* 」 */
        if (low == 0x10) return glyph_bracket_open;    /* 【 */
        if (low == 0x11) return glyph_bracket_close;   /* 】 */
        if (low == 0x26) return glyph_jp_bullet;       /* ・ */
    } else if (high == 0x22) {
        if (low == 0x1A) return glyph_jp_colon;        /* ： */
        if (low == 0x0F) return glyph_jp_bullet;       /* ／ */
    }

    memset(g_glyph_buffer, 0, sizeof(g_glyph_buffer));

    /* Build balanced, clean stroke geometry based on Unicode/TRON codepoint */
    uint32_t seed = ((uint32_t)high << 16) | (uint32_t)low | 0x9E3779B9;
    seed = seed * 1664525u + 1013904223u;

    if (high == 0x24 || high == 0x25) {
        /* Kana (Hiragana / Katakana): flowing curves and distinct strokes */
        int type = (low ^ (low >> 2)) % 6;
        for (int r = 2; r < 14; r++) {
            int c1 = 4 + ((r * 3 + (low & 7)) % 8);
            int c2 = 12 - ((r * 2 + (low >> 3)) % 7);
            if (c1 >= 2 && c1 <= 14) g_glyph_buffer[r * 2 + (c1 / 8)] |= (0x80 >> (c1 % 8));
            if (c2 >= 2 && c2 <= 14) g_glyph_buffer[r * 2 + (c2 / 8)] |= (0x80 >> (c2 % 8));
        }
        /* Top horizontal bar */
        if (type <= 3) {
            g_glyph_buffer[3 * 2 + 0] |= 0x3F;
            g_glyph_buffer[3 * 2 + 1] |= 0xFC;
        }
        /* Mid horizontal bar */
        if (type == 1 || type == 4) {
            g_glyph_buffer[7 * 2 + 0] |= 0x1F;
            g_glyph_buffer[7 * 2 + 1] |= 0xF0;
        }
        /* Vertical center spine */
        for (int r = 3; r < 14; r++) {
            g_glyph_buffer[r * 2 + 0] |= 0x08;
        }
    } else {
        /* Kanji CJK Ideographs: structured radicals, horizontal/vertical strokes */
        /* Top radical / Roof */
        int roof_type = (seed >> 8) % 4;
        if (roof_type == 0) {
            /* Dot + horizontal roof (亠 / 宀) */
            g_glyph_buffer[2 * 2 + 0] |= 0x08;
            g_glyph_buffer[3 * 2 + 0] |= 0x7F;
            g_glyph_buffer[3 * 2 + 1] |= 0xFE;
        } else if (roof_type == 1) {
            /* Grass radical (艹) */
            g_glyph_buffer[2 * 2 + 0] |= 0x48;
            g_glyph_buffer[2 * 2 + 1] |= 0x90;
            g_glyph_buffer[3 * 2 + 0] |= 0x7F;
            g_glyph_buffer[3 * 2 + 1] |= 0xFE;
            g_glyph_buffer[4 * 2 + 0] |= 0x48;
            g_glyph_buffer[4 * 2 + 1] |= 0x90;
        } else {
            /* Top bar */
            g_glyph_buffer[2 * 2 + 0] |= 0x3F;
            g_glyph_buffer[2 * 2 + 1] |= 0xFC;
        }

        /* Left radical / side (亻, 氵, 木, 言, etc.) */
        int left_type = (seed >> 12) % 4;
        if (left_type == 0) {
            /* Person radical (亻) */
            g_glyph_buffer[4 * 2 + 0] |= 0x20;
            g_glyph_buffer[5 * 2 + 0] |= 0x40;
            for (int r = 6; r < 14; r++) g_glyph_buffer[r * 2 + 0] |= 0x20;
        } else if (left_type == 1) {
            /* Tree / Water (木 / 氵) */
            g_glyph_buffer[5 * 2 + 0] |= 0x70;
            for (int r = 4; r < 14; r++) g_glyph_buffer[r * 2 + 0] |= 0x20;
            g_glyph_buffer[9 * 2 + 0] |= 0x50;
        } else {
            /* Left vertical border */
            for (int r = 4; r < 14; r++) g_glyph_buffer[r * 2 + 0] |= 0x40;
        }

        /* Center / Right Body */
        int mid_type = (seed >> 16) % 4;
        if (mid_type == 0) {
            /* Sun / Moon / Field box (日 / 月 / 田) */
            for (int r = 5; r < 13; r++) {
                g_glyph_buffer[r * 2 + 0] |= 0x02;
                g_glyph_buffer[r * 2 + 1] |= 0x80;
            }
            g_glyph_buffer[5 * 2 + 0] |= 0x03;
            g_glyph_buffer[5 * 2 + 1] |= 0xC0;
            g_glyph_buffer[8 * 2 + 0] |= 0x03;
            g_glyph_buffer[8 * 2 + 1] |= 0xC0;
            g_glyph_buffer[12 * 2 + 0] |= 0x03;
            g_glyph_buffer[12 * 2 + 1] |= 0xC0;
        } else if (mid_type == 1) {
            /* Cross / Tree structure (十 / 木) */
            g_glyph_buffer[7 * 2 + 0] |= 0x07;
            g_glyph_buffer[7 * 2 + 1] |= 0xE0;
            for (int r = 4; r < 14; r++) g_glyph_buffer[r * 2 + 0] |= 0x04;
            g_glyph_buffer[11 * 2 + 0] |= 0x0A;
            g_glyph_buffer[11 * 2 + 1] |= 0xA0;
        } else {
            /* Multi-bar ideograph */
            g_glyph_buffer[6 * 2 + 0] |= 0x07;
            g_glyph_buffer[6 * 2 + 1] |= 0xE0;
            g_glyph_buffer[9 * 2 + 0] |= 0x07;
            g_glyph_buffer[9 * 2 + 1] |= 0xE0;
            for (int r = 5; r < 14; r++) g_glyph_buffer[r * 2 + 1] |= 0x20;
        }

        /* Bottom foundation bar */
        g_glyph_buffer[13 * 2 + 0] |= 0x3F;
        g_glyph_buffer[13 * 2 + 1] |= 0xFE;
    }

    return g_glyph_buffer;
}

#include <btron/jis_fonts.h>

const UB* get_glyph_bitmap(TC code, H *out_width, H *out_height) {
    if (code < 128) {
        if (out_width) *out_width = 8;
        if (out_height) *out_height = 16;
        return font_ascii_8x16[code];
    }

    if (out_width) *out_width = 16;
    if (out_height) *out_height = 16;

    char utf8_buf[8];
    int n = tc_to_utf8(code, utf8_buf, sizeof(utf8_buf));
    if (n >= 3) {
        UW cp = (((unsigned char)utf8_buf[0] & 0x0F) << 12) |
                (((unsigned char)utf8_buf[1] & 0x3F) << 6) |
                ((unsigned char)utf8_buf[2] & 0x3F);

        const UB *bmp = get_jis_glyph_bitmap(cp);
        if (bmp) {
            return bmp;
        }
    }

    return synthesize_japanese_glyph(code);
}

static ER render_tc_string(GDEV *dev, H x, H y, const char *text, COLOR fg_col, COLOR bg_col, BOOL is_underlined, BOOL is_dotted) {
    if (!dev || !text || !dev->pixels) return E_PAR;

    H cur_x = x;
    H cur_y = y;
    const char *p = text;
    volatile COLOR *pix = (volatile COLOR*)dev->pixels;
    H width = dev->width;

    while (*p) {
        if (*p == '\n') {
            cur_x = x;
            cur_y += 18;
            p++;
            continue;
        }

        int consumed = 0;
        TC code = utf8_to_tc(p, &consumed);
        p += (consumed > 0 ? consumed : 1);

        H gw = 8, gh = 16;
        const UB *bmp = get_glyph_bitmap(code, &gw, &gh);
        if (!bmp) continue;

        for (int row = 0; row < gh; row++) {
            H py = cur_y + row;
            if (py < dev->clip.top || py >= dev->clip.bottom) continue;

            if (gw <= 8) {
                UB line = bmp[row];
                for (int col = 0; col < gw; col++) {
                    H px = cur_x + col;
                    if (px >= dev->clip.left && px < dev->clip.right) {
                        if (line & (0x80 >> col)) {
                            pix[py * width + px] = fg_col;
                        } else if (bg_col != 0x00000000) {
                            pix[py * width + px] = bg_col;
                        }
                    }
                }
            } else {
                UB b0 = bmp[row * 2];
                UB b1 = bmp[row * 2 + 1];
                for (int col = 0; col < 16; col++) {
                    H px = cur_x + col;
                    if (px >= dev->clip.left && px < dev->clip.right) {
                        UB bit = (col < 8) ? (b0 & (0x80 >> col)) : (b1 & (0x80 >> (col - 8)));
                        if (bit) {
                            pix[py * width + px] = fg_col;
                        } else if (bg_col != 0x00000000) {
                            pix[py * width + px] = bg_col;
                        }
                    }
                }
            }
        }

        /* TIP Feedback: underline ONLY when explicitly requested */
        if (is_underlined) {
            H underline_y = cur_y + gh - 1;
            if (underline_y >= dev->clip.top && underline_y < dev->clip.bottom) {
                for (int col = 0; col < gw; col++) {
                    H px = cur_x + col;
                    if (px >= dev->clip.left && px < dev->clip.right) {
                        if (!is_dotted || (col % 2 == 0)) {
                            pix[underline_y * width + px] = fg_col;
                        }
                    }
                }
            }
        }

        cur_x += gw;
    }

    return E_OK;
}

ER drw_tc_string(GDEV *dev, H x, H y, const char *text, COLOR fg_col, COLOR bg_col) {
    return render_tc_string(dev, x, y, text, fg_col, bg_col, FALSE, FALSE);
}

ER drw_tc_string_underlined(GDEV *dev, H x, H y, const char *text, COLOR fg_col, COLOR bg_col, BOOL dotted) {
    return render_tc_string(dev, x, y, text, fg_col, bg_col, TRUE, dotted);
}
